// Vendors the shared core hmnsq/subcore by version and commit (Guidelines 4.1, 4.4).
//   node tools/vendor_subcore.mjs [--subcore ../subcore] [--rev HEAD] [--check]
// The files are taken from a commit of the subcore repository (git archive), never from its working tree,
// so the PROVENANCE commit names exactly what was copied. What is copied:
//   docs/src/*.js               -> docs/vendor/subcore/<version>/src/
//   docs/vendor/js-yaml/<v>/     -> docs/vendor/subcore/<version>/vendor/js-yaml/<v>/  (spec.js imports it as
//                                   '../vendor/js-yaml/...', so the relative import is unchanged)
//   spec/models, spec/schema, spec/substrates, spec/realisations, spec/grammar, vectors (when present at the commit)
//                               -> docs/vendor/subcore/<version>/spec/... and .../vectors/...
//   docs/API.md, LICENSE, VERSION
// The vendored copy is never edited. --check recomputes the file hashes and compares them with PROVENANCE.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { REPO } from './record.mjs';

const NOTICE = '© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI.';

function args() {
  const a = { subcore: path.resolve(REPO, '..', 'subcore'), rev: 'HEAD', check: false };
  const v = process.argv.slice(2);
  for (let i = 0; i < v.length; i++) {
    if (v[i] === '--subcore') a.subcore = path.resolve(v[++i]);
    else if (v[i] === '--rev') a.rev = v[++i];
    else if (v[i] === '--check') a.check = true;
    else throw new Error(`vendor_subcore: unknown option ${v[i]}`);
  }
  return a;
}

const git = (dir, ...x) => execFileSync('git', ['-C', dir, ...x], { encoding: 'utf8', maxBuffer: 1 << 28 });
const sha256 = (b) => createHash('sha256').update(b).digest('hex');

function walk(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((x, y) => (x.name < y.name ? -1 : 1))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p, base)); else out.push(path.relative(base, p));
  }
  return out;
}

function main() {
  const a = args();
  const commit = git(a.subcore, 'rev-parse', a.rev).trim();
  const tree = git(a.subcore, 'rev-parse', `${commit}^{tree}`).trim();
  const version = git(a.subcore, 'show', `${commit}:VERSION`).trim();
  const dest = path.join(REPO, 'docs', 'vendor', 'subcore', version);
  if (a.check) {
    const prov = fs.readFileSync(path.join(dest, 'PROVENANCE'), 'utf8');
    let bad = 0;
    for (const line of prov.split('\n')) {
      const m = /^([0-9a-f]{64})  (.+)$/.exec(line);
      if (!m) continue;
      const p = path.join(dest, m[2]);
      const got = fs.existsSync(p) ? sha256(fs.readFileSync(p)) : 'missing';
      if (got !== m[1]) { console.log(`differs: ${m[2]}`); bad++; }
    }
    const listed = new Set(prov.split('\n').map((l) => /^[0-9a-f]{64}  (.+)$/.exec(l)).filter(Boolean).map((m) => m[1]));
    for (const f of walk(dest)) if (f !== 'PROVENANCE' && !listed.has(f)) { console.log(`not in PROVENANCE: ${f}`); bad++; }
    const pc = /commit: ([0-9a-f]{40})/.exec(prov);
    console.log(`[vendor_subcore] check ${dest}: ${bad} differences; vendored commit ${pc && pc[1]}; subcore ${a.rev} is ${commit}`);
    if (pc && pc[1] !== commit) console.log('[vendor_subcore] the subcore commit has moved since vendoring: re-vendor with node tools/vendor_subcore.mjs');
    process.exit(bad ? 1 : 0);
  }
  const all = git(a.subcore, 'ls-tree', '-r', '--name-only', commit).split('\n').filter(Boolean);
  const pick = [];
  for (const f of all) {
    let to = null;
    if (/^docs\/src\/[^/]+\.js$/.test(f)) to = f.replace(/^docs\/src\//, 'src/');
    else if (f.startsWith('docs/vendor/js-yaml/')) to = f.replace(/^docs\/vendor\//, 'vendor/');
    else if (/^spec\/(models|schema|substrates|realisations|grammar)\//.test(f)) to = f;
    else if (f.startsWith('vectors/')) to = f;
    else if (f === 'docs/API.md') to = 'API.md';
    else if (f === 'LICENSE') to = 'LICENCE';
    else if (f === 'VERSION') to = 'VERSION';
    if (to) pick.push([f, to]);
  }
  fs.rmSync(dest, { recursive: true, force: true });
  const hashes = [];
  for (const [f, to] of pick) {
    const buf = execFileSync('git', ['-C', a.subcore, 'show', `${commit}:${f}`], { maxBuffer: 1 << 28 });
    const p = path.join(dest, to);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, buf);
    hashes.push(`${sha256(buf)}  ${to}`);
  }
  hashes.sort((x, y) => (x.slice(66) < y.slice(66) ? -1 : 1));
  const prov = [
    `# ${NOTICE} SPDX-License-Identifier: CC0-1.0`,
    '# Provenance of the vendored shared core. Generated by tools/vendor_subcore.mjs; never edited by hand.',
    'name: subcore',
    'upstream: hmnsq/subcore (local repository /home/user/build/subcore during the build)',
    `version: ${version}`,
    `commit: ${commit}`,
    `tree: ${tree}`,
    'licence: GPL-3.0-or-later (code); CC0-1.0 (schemas, models and data); js-yaml carries its own MIT licence',
    'method: git show <commit>:<path> for every file below; the working tree of subcore is not read',
    `files: ${hashes.length}`,
    'sha256:',
    ...hashes,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(dest, 'PROVENANCE'), prov);
  console.log(`[vendor_subcore] subcore ${version} at ${commit}: ${hashes.length} files into ${path.relative(REPO, dest)}`);
}

main();
